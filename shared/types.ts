/**
 * 多人时间表 · 前后端共用契约（第 1 格定稿）
 *
 * 契约版本：v1.1 · 2026-11-15
 *   v1.0 是上一轮的草稿，v1.1 是评审后的定稿。
 *   升版本规则：新增「可选字段」是安全扩展（旧客户端读不到就当没有），升次版本；
 *   改掉 / 删掉已有字段、改字段含义、改错误优先级，属于破坏性变更，
 *   升主版本并通知所有调用方（第 5 格加登录就是这种）。
 *
 * 本文件里没有任何「会执行的代码」，只有 TypeScript 类型。
 * 它的作用是把「前端要传什么、后端要回什么、出错长什么样」
 * 写成一份双方都必须遵守的书面约定。
 *
 * 【为什么契约先于代码】
 *   前后端分离的本质不是「两个文件夹」，而是「两边互相看不见对方内部，
 *   只认中间这份约定」。前端不知道有 SQLite，后端不知道页面上有绿格子。
 *   放在 shared/ 是因为它是唯一来源：谁也不拥有它，改一个字段两边编译器同时报错。
 *
 * 【编译期 vs 运行时】
 *   interface / type 在编译后会被擦除，浏览器和 Node 都看不到它们。
 *   HTTP 上传的是 JSON 字符串 / 查询串，不是类型。
 *   所以契约里还必须写清「线上格式」（见文末 API 清单）；
 *   类型只是帮我们在写码时提前发现拼错，不能替代运行时的校验
 *   —— 网络对面照样能发 `?minMinutes=abc` 过来，编译器管不到别人。
 *
 * 【术语与时间格式】
 *   内部计算用「从 00:00 起算的分钟数」：数字负责可算，字符串负责可读，
 *   两者之间的转换是后端的事，前端不算。
 *   接口里两种字符串各管各的场景，别混：
 *     - 日期单独传 "YYYY-MM-DD"；一天的范围、忙碌起止用 "HH:mm"（如 "09:00"）。
 *     - 返回的空闲段 start / end 用完整本地时间戳 "YYYY-MM-DDTHH:mm"，
 *       不带时区，避免 UTC 换算把日期挪走（见 TimeSlot）。
 */

// ============================================================
// 一、统一响应包装
// ============================================================

/**
 * 所有接口，无论成功失败，都回这个形状。
 * 前端只写一次「解包」逻辑就能服务全部接口，也不用靠状态码猜 body 里装了什么。
 *
 * success:false 分支里两个字段各有分工：
 *   - code：给程序判断的稳定错误码，写死后不改，前端靠它决定高亮哪个输入框。
 *   - error：给用户看的中文文案，可以改措辞、以后可以换语言，别拿它做判断。
 *   code 是可选字段：老版本响应不带它也合法，前端读不到就只显示 error。
 *   光靠 error.includes("date") 之类比对，后端改一个字前端就失灵。
 */
export type ApiResponse<T> =
  | { success: true; data: T }
  | { success: false; error: string; code?: ErrorCode }

/** 常见错误码。新增只能往后加，已有的值不许改含义（改了等于破坏性变更）。 */
export type ErrorCode =
  | 'INVALID_DATE'
  | 'INVALID_TIME'
  | 'INVALID_PARAMETER'
  | 'NAME_EMPTY'
  | 'NAME_DUPLICATE'
  | 'USER_NOT_FOUND'
  | 'NOT_FOUND'
  | 'INTERNAL_ERROR'

// ============================================================
// 二、数据模型（对应数据库里的两张表）
// ============================================================

/** 一个参与成员 */
export interface User {
  /** 服务端生成的唯一 id。绝不让前端自己造：id 的生成规则属于服务端 */
  id: string
  name: string
  /** 前端画忙碌块用的颜色，纯展示字段，后端不解释它的含义 */
  color: string
}

/**
 * 一条「忙」时段。这是本项目唯一的原始数据。
 *
 * 库里存的是「谁在什么时候忙」，不存「谁在什么时候空」。
 * 「共同空闲」是算出来的结论，不是存进去的数据 —— 这条边界决定了
 * 后面整个项目的分层（见第四节）。
 */
export interface Event {
  id: string
  userId: string
  /** YYYY-MM-DD */
  date: string
  /** HH:mm，含 */
  startTime: string
  /** HH:mm，不含（半开区间，避免 09:00-10:00 与 10:00-11:00 被误判重叠） */
  endTime: string
  title: string
}

/** 列表接口带上成员信息，前端不用为了显示名字再发一次请求 */
export interface EventWithUser extends Event {
  user: User
}

// ============================================================
// 三、每个接口的输入 / 输出
// ============================================================

/** POST /api/users 的请求体 */
export interface CreateUserInput {
  name: string
  /**
   * 可选：不传时由后端分配默认调色板里的颜色。
   * 需求表第 2 节写的是「姓名 + 标识色」，草稿漏收了这个键；
   * 定为可选，老客户端不传也照样能建成员（安全扩展）。
   */
  color?: string
}

/** POST /api/events 的请求体 */
export interface CreateEventInput {
  userId: string
  date: string
  startTime: string
  endTime: string
  title: string
}

/** 一段连续的可安排时间 */
export interface TimeSlot {
  /** 本地时间字符串 YYYY-MM-DDTHH:mm，不带时区，避免 UTC 换算把日期挪走 */
  start: string
  end: string
  /**
   * 由后端算好一并返回。前端不要自己用 end - start 再算一遍：
   * 两边各算一遍，迟早会在某处对不上。规则只留一份。
   */
  durationMinutes: number
}

/** GET /api/free-slots 的查询参数 */
export interface FreeSlotQuery {
  date: string
  /** 不传就用后端默认值 08:00 */
  dayStart?: string
  /** 不传就用后端默认值 22:00 */
  dayEnd?: string
  /** 短于这个分钟数的空闲段被丢弃，默认 30 */
  minMinutes?: number
  /** 通勤 / 准备缓冲，默认 15。可选：不传不影响旧客户端 */
  bufferMinutes?: number
}

/** GET /api/free-slots 的返回 */
export interface FreeSlotResult {
  date: string
  dayStart: string
  dayEnd: string
  /** 回显：本次实际采用的最短时长 */
  minMinutes: number
  /** 回显：本次实际采用的缓冲分钟数。前端没传时，这里是后端默认值 15 */
  bufferMinutes: number
  userCount: number
  slots: TimeSlot[]
}

