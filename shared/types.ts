/**
 * 多人时间表 · 前后端共用契约（第 1 格定稿）
 *
 * 契约版本：v2.0 · 2026-11-21
 *   v1.0 是草稿，v1.1 是评审后的定稿。
 *   v1.2（第 4 格实现期）：补上 POST /api/events 漏写的错误码，
 *     并新增 DUPLICATE_EVENT（同一人、同一天、起止完全相同 → 409）。
 *     只加不改：老客户端遇到不认识的 code 就显示 error 文案兜底，属于安全扩展，升次版本。
 *   v2.0（第 5 格加登录，破坏性变更）：
 *     - POST /api/events 的请求体删掉 userId，身份改由会话（cookie）决定；
 *     - 所有写接口要求登录，未登录 → 401 UNAUTHENTICATED；
 *     - DELETE /api/events/:id 只能删自己的，删别人的 → 403 FORBIDDEN；
 *     - 新增 POST /api/login、POST /api/logout、GET /api/me；
 *     - 删除 POST /api/users，改为公开的 POST /api/register（自己给自己开户）；
 *     - DELETE /api/users/:id 只能注销自己，删别人的 → 403 FORBIDDEN；
 *     - 新增错误码 UNKNOWN_FIELD / UNAUTHENTICATED / LOGIN_FAILED / FORBIDDEN。
 *     删字段 + 新增 401 = 老客户端必然失败，所以升主版本，不能当安全扩展。
 *
 *     ⚠️ v2.0 的这两条（删 POST /api/users、删人只能删自己）是**在发布前**补进去的，
 *     所以仍然算 v2.0，不升 v2.1 / v3.0。<-- 这条规矩值得记住：
 *     版本号管的是「已经交出去的东西」。还没提交、没推远程、没有外部调用方时，
 *     契约只是本地草稿，改它就是改草稿；一旦发布，同样的改动就必须升版本 +
 *     通知所有调用方。代价差别非常大。
 *
 *   升版本规则：新增「可选字段」是安全扩展（旧客户端读不到就当没有），升次版本；
 *   改掉 / 删掉已有字段、改字段含义、改错误优先级，属于破坏性变更，
 *   升主版本并通知所有调用方（第 5 格加登录就是这种）。
 *
 * 本文件里没有任何「会执行的代码」，只有 TypeScript 类型。
 * 它的作用是把「前端要传什么、后端要回什么、出错长什么样」
 * 写成一份双方都必须遵守的书面约定。
 *
 * 【为什么契约先于代码】
 *   前后端分离的本质不是「两个文件夹」，而是「两边互相看不见对方内部，
 *   只认中间这份约定」。前端不知道有 SQLite，后端不知道页面上有绿格子。
 *   放在 shared/ 是因为它是唯一来源：谁也不拥有它，改一个字段两边编译器同时报错。
 *
 * 【编译期 vs 运行时】
 *   interface / type 在编译后会被擦除，浏览器和 Node 都看不到它们。
 *   HTTP 上传的是 JSON 字符串 / 查询串，不是类型。
 *   所以契约里还必须写清「线上格式」（见文末 API 清单）；
 *   类型只是帮我们在写码时提前发现拼错，不能替代运行时的校验
 *   —— 网络对面照样能发 `?minMinutes=abc` 过来，编译器管不到别人。
 *
 * 【术语与时间格式】
 *   内部计算用「从 00:00 起算的分钟数」：数字负责可算，字符串负责可读，
 *   两者之间的转换是后端的事，前端不算。
 *   接口里两种字符串各管各的场景，别混：
 *     - 日期单独传 "YYYY-MM-DD"；一天的范围、忙碌起止用 "HH:mm"（如 "09:00"）。
 *     - 返回的空闲段 start / end 用完整本地时间戳 "YYYY-MM-DDTHH:mm"，
 *       不带时区，避免 UTC 换算把日期挪走（见 TimeSlot）。
 */

// ============================================================
// 一、统一响应包装
// ============================================================

/**
 * 所有接口，无论成功失败，都回这个形状。
 * 前端只写一次「解包」逻辑就能服务全部接口，也不用靠状态码猜 body 里装了什么。
 *
 * success:false 分支里两个字段各有分工：
 *   - code：给程序判断的稳定错误码，写死后不改，前端靠它决定高亮哪个输入框。
 *   - error：给用户看的中文文案，可以改措辞、以后可以换语言，别拿它做判断。
 *   code 是可选字段：老版本响应不带它也合法，前端读不到就只显示 error。
 *   光靠 error.includes("date") 之类比对，后端改一个字前端就失灵。
 */
export type ApiResponse<T> =
  | { success: true; data: T }
  | { success: false; error: string; code?: ErrorCode }

/** 常见错误码。新增只能往后加，已有的值不许改含义（改了等于破坏性变更）。 */
export type ErrorCode =
  // ---- 参数与数据（v1.x）----
  | 'INVALID_DATE'
  | 'INVALID_TIME'
  | 'INVALID_PARAMETER'
  | 'NAME_EMPTY'
  | 'NAME_DUPLICATE'
  /** v2.0 起 POST /api/events 不再返回它：身份来自会话，"查无此人"不成立 */
  | 'USER_NOT_FOUND'
  | 'DUPLICATE_EVENT'
  | 'NOT_FOUND'
  | 'INTERNAL_ERROR'
  // ---- 身份与权限（v2.0 新增）----
  /** 401：没登录，或者会话已失效（后端重启后就会失效，见「认证与会话」） */
  | 'UNAUTHENTICATED'
  /** 401：登录时姓名或密码不对。故意不区分是哪一个错，避免被人试出谁有账号 */
  | 'LOGIN_FAILED'
  /** 403：登录了，但这条数据不归你（删别人的忙碌） */
  | 'FORBIDDEN'
  /** 400：请求体里带了契约已经删掉的字段（例如老的 userId），说明调用方还是旧版本 */
  | 'UNKNOWN_FIELD'

