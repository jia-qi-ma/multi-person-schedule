// 四、业务规则（先用文字定死，第 4 格才翻译成代码）
// ============================================================

/**
 * 【算法层：共同空闲是算出来的事实】
 *   在 [dayStart, dayEnd) 内，取所有成员忙碌时段的并集，从这一天里扣掉，
 *   剩下的每段连续区间就是共同空闲。
 *
 * 只要有一个人忙，这段时间就不算全员空闲 —— 所以不同人的忙时段是
 * 「合并」关系，不是「取交集」。这一点是本项目最容易写反的地方。
 *
 * 例：A 忙 09:00-11:00，B 忙 10:00-12:00
 *   合并后 09:00-12:00 连成一整片 → 08:00-09:00 与 12:00-22:00 才是空闲。
 *
 * 这条规则必须由后端实现，理由：
 *   ① 它依赖库里的全量数据，前端只看得见自己请求到的那部分；
 *   ② 换成 App / 换成别的语言重写前端，规则不该跟着重写一遍；
 *   ③ 前端自己算，就会和后端返回的 slots 出现两个真相。
 *
 * 【产品规则层：两条独立规则，按固定顺序执行】
 *   ① 通勤缓冲 bufferMinutes（默认 15）：
 *      先取所有忙碌时段的并集，得到合并后的忙碌块；
 *      对每个忙碌块，在其前后各扣除 bufferMinutes 分钟，得到「修正后的空闲段」。
 *      锚点是忙碌块，所以只有贴着忙碌的空闲段会被削，孤立的空闲段分毫不动
 *      （例如 15:00-16:00 前后谁都不忙，完整保留）。
 *      必须用并集后的块：逐条对原始记录扣，会在本就全员忙的重叠处产生无效缓冲。
 *
 *   ② 最短可用时长 minMinutes（默认 30）：
 *      拿 ① 修正后的段去比长度，短于阈值的整段丢弃。
 *
 *   顺序不可颠倒。先判 30 分钟再扣缓冲，会把一段扣完只剩 20 分钟的时段
 *   判成「可用」，页面安静地显示一条违反自己规则的时段，联调极难查。
 *
 *   两条规则各自独立、不合并：一个按整段长度全局筛，一个贴忙碌边缘局部扣。
 *   合成同一个阈值，会误伤前后都不忙的 60 分钟段。
 *
 *   默认值都归后端，请求可用可选参数覆盖；不传时响应照样回显实际采用值。
 *
 *   基线（08:00-22:00，张三 09:00-11:00、李四 10:00-12:00，默认 30 / 15）：
 *     并集 09:00-12:00 → 前后各扣 15 → 08:00-08:45 与 12:15-22:00
 *     （08:00-09:00 尾部扣掉 15；12:00-22:00 头部扣掉 15）
 */

