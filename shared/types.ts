/** 一个参与成员 */
export interface User {
  /** 服务端生成的唯一 id。绝不让前端自己造：id 的生成规则属于服务端 */
  id: string
  name: string
  /** 前端画忙碌块用的颜色，纯展示字段，后端不解释它的含义 */
  color: string
  /**
   * 注意这里**没有** password / password_hash。
   * 数据库里存的是 scrypt 哈希，但任何响应都不带它。
   * 契约里不写这个字段，就是「它不可能被返回」的书面保证 ——
   * 前端拿不到，也就不会有「顺手打到日志里」的机会。
   */
}

/**
 * 一条「忙」时段。这是本项目唯一的原始数据。
 *
 * 库里存的是「谁在什么时候忙」，不存「谁在什么时候空」。
 * 「共同空闲」是算出来的结论，不是存进去的数据 —— 这条边界决定了
 * 后面整个项目的分层（见第四节）。
 */
export interface Event {
  id: string
  userId: string
  /** YYYY-MM-DD */
  date: string
  /** HH:mm，含 */
  startTime: string
  /** HH:mm，不含（半开区间，避免 09:00-10:00 与 10:00-11:00 被误判重叠） */
  endTime: string
  title: string
}

/** 列表接口带上成员信息，前端不用为了显示名字再发一次请求 */
export interface EventWithUser extends Event {
  user: User
}

