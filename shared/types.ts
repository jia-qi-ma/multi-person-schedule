/**
 * POST /api/register 的请求体。
 *
 * 为什么是「注册」而不是「加成员」：
 *   原来的 POST /api/users 是「登录后替别人开户」，等于谁都能造账号；
 *   而删人只能删自己（见 DELETE /api/users/:id），造出来的账号谁也清不掉。
 *   改成注册之后，成员一定是本人建的，权责一致：自己的账号自己注册、自己注销。
 *   附带的好处：注册不需要登录，新人加入不依赖任何现有成员。
 *
 * 代价写在契约的【范围边界】里：注册是公开的，等于谁都能加入这个时间表。
 * 真实产品要加邀请码或管理员审批，那是另一层。
 */
export interface RegisterInput {
  name: string
  /**
   * 自己设的登录密码，必填。
   * 不给密码，这个人就永远登不进来，「成员」和「账号」会变成两套东西。
   * 后端只把它变成 scrypt 哈希存库，不回显、不记录。
   */
  password: string
  /**
   * 可选：不传时由后端分配默认调色板里的颜色。
   * 需求表第 2 节写的是「姓名 + 标识色」，草稿漏收了这个键。
   */
  color?: string
}

/**
 * POST /api/events 的请求体。
 *
 * v2.0 起**没有 userId**：谁是这条记录的主人，由服务端从会话里读。
 * 原因不是"少传一个字段更省事"，而是安全边界：
 * 只要服务端还收客户端送来的身份，任何能发请求的人都能冒充别人录数据，
 * 登录就变成只挡住页面、挡不住请求的装饰品。
 */
export interface CreateEventInput {
  date: string
  startTime: string
  endTime: string
  title: string
}

/** POST /api/login 的请求体 */
export interface LoginInput {
  name: string
  password: string
}

/** POST /api/logout 的返回。重复登出也算成功（幂等），不给前端添负担 */
export interface LogoutResult {
  loggedOut: boolean
}

/** 一段连续的可安排时间 */
export interface TimeSlot {
  /** 本地时间字符串 YYYY-MM-DDTHH:mm，不带时区，避免 UTC 换算把日期挪走 */
  start: string
  end: string
  /**
   * 由后端算好一并返回。前端不要自己用 end - start 再算一遍：
   * 两边各算一遍，迟早会在某处对不上。规则只留一份。
   */
  durationMinutes: number
}

/** GET /api/free-slots 的查询参数 */
export interface FreeSlotQuery {
  date: string
  /** 不传就用后端默认值 08:00 */
  dayStart?: string
  /** 不传就用后端默认值 22:00 */
  dayEnd?: string
  /** 短于这个分钟数的空闲段被丢弃，默认 30 */
  minMinutes?: number
  /** 通勤 / 准备缓冲，默认 15。可选：不传不影响旧客户端 */
  bufferMinutes?: number
}

/** GET /api/free-slots 的返回 */
export interface FreeSlotResult {
  date: string
  dayStart: string
  dayEnd: string
  /** 回显：本次实际采用的最短时长 */
  minMinutes: number
  /** 回显：本次实际采用的缓冲分钟数。前端没传时，这里是后端默认值 15 */
  bufferMinutes: number
  userCount: number
  slots: TimeSlot[]
}

